import { createContext, useContext } from 'react'

/**
 * Доступ к окну с формой.
 *
 * Форма живёт внизу страницы, но добираться до неё прокруткой через
 * весь сайт — плохой ответ на нажатие «Обсудить проект». Поэтому её
 * можно открыть окном откуда угодно.
 *
 * Контекст лежит отдельным файлом, чтобы обновление модулей на лету
 * не роняло состояние при каждой правке разметки окна.
 */
export const RequestCtx = createContext<() => void>(() => {})

/** Открыть окно с формой. */
export const useRequest = () => useContext(RequestCtx)
