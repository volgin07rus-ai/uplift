/* ================================================================
   1. Куда уходит заявка
   ================================================================

   Сам сайт письмо отправить не может: GitHub Pages отдаёт файлы и не
   выполняет код. Поэтому отправкой занимается отдельная функция —
   она лежит в api/request.mjs и разворачивается отдельно от сайта.

   Сюда — её адрес, что-то вроде
   https://uplift-mail.vercel.app/api/request
*/
export const REQUEST_ENDPOINT = 'https://scroll-tied-video.vercel.app/api/request'

/*
  Адреса получателя здесь нет намеренно.

  Всё, что лежит в этом файле, попадает в собранный скрипт и видно
  любому, кто откроет сайт. Почтовый ящик оттуда собрали бы роботы, а
  ящик к тому же чужой. Он нужен только серверной функции — и живёт
  в её переменной окружения NOTIFY_EMAIL, куда браузер не заглядывает.
*/

/** Настроена ли отправка. Пока нет — форма ничего никуда не шлёт. */
export const formConfigured = () => !REQUEST_ENDPOINT.startsWith('*')

/*
  Текст письма складывает сама функция, а не браузер. Так надо: приходи
  текст готовым, любой мог бы отправить с вашего адреса что угодно.
  Поэтому ФИО и ссылка на сайт живут в настройках функции, а не здесь.
*/

/* ================================================================
   2. Телеграм-бот
   ================================================================

   Имя бота без собачки — то, что выдал BotFather. Сюда же человек
   уходит после отправки заявки. Код самого бота лежит в bot/.
*/
export const TELEGRAM_BOT = 'uplift_agency_bot'

/** Метка в диплинке: по ней бот понимает, что человек пришёл с сайта. */
export const TELEGRAM_START_PAYLOAD = 'zayavka'

/** Ссылка на бота с меткой. Пустая, пока имя не подставлено. */
export const telegramLink = () =>
  TELEGRAM_BOT.startsWith('*')
    ? ''
    : `https://t.me/${TELEGRAM_BOT}?start=${TELEGRAM_START_PAYLOAD}`
